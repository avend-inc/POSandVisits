-- ============================================================
--  店舗に「ダッシュボード表示」フラグ(visible)を追加
--
--  ・35店以上あるので、管理画面で店ごとに「出す/隠す」を切り替えられるようにする。
--  ・非表示にした店は、各ダッシュボードの一覧・店舗選択・合計から外れる
--    （データ取り込みは続く。あくまで“表示”の切り替え）。
--  ・既定は true（全店表示）。既存店は自動的に true になる。
-- ============================================================
alter table public.stores
  add column if not exists visible boolean not null default true;
